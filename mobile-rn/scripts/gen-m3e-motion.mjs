// Generates src/theme/m3e-motion.generated.ts from the published @m3e/web
// motion scheme (the springs Material 3 Expressive defines). @m3e/web is a
// Lit/DOM library and cannot run inside React Native, so its numeric tokens
// are the part we consume. Run: npm run gen:m3e
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(
  path.join(root, 'node_modules/@m3e/web/dist/theme.js'),
  'utf8',
);

const start = source.indexOf('const MotionSchemeSprings = {');
const end = source.indexOf('/** The number of samples', start);
if (start < 0 || end < 0) throw new Error('MotionSchemeSprings not found in @m3e/web');
const block = source.slice(start, end);
const [standardPart, expressivePart] = block.split('expressive:');

const entry =
  /"([a-z-]+)":\s*\{\s*damping:\s*([\d.]+),\s*stiffness:\s*([\d.]+),\s*duration:\s*([\d.]+)\s*\}/g;

function parse(part) {
  const out = {};
  for (const m of part.matchAll(entry)) {
    out[m[1]] = {
      damping: Number(m[2]),
      stiffness: Number(m[3]),
      duration: Number(m[4]),
    };
  }
  return out;
}

const motion = { standard: parse(standardPart), expressive: parse(expressivePart) };
if (Object.keys(motion.expressive).length !== 6) throw new Error('unexpected token count');

const out = `// GENERATED by scripts/gen-m3e-motion.mjs from @m3e/web ${JSON.parse(
  fs.readFileSync(path.join(root, 'node_modules/@m3e/web/package.json'), 'utf8'),
).version}. Do not edit by hand.
export const M3E_SPRINGS = ${JSON.stringify(motion, null, 2)} as const;
`;
fs.writeFileSync(path.join(root, 'src/theme/m3e-motion.generated.ts'), out);
console.log('wrote src/theme/m3e-motion.generated.ts');
